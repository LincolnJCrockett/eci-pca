import sys, pandas as pd
d = pd.read_csv(sys.argv[1])
print(d.shape, d.model_id.nunique(), "models", d.benchmark_id.nunique(), "benchmarks")
print("dups model-bench:", d.duplicated(["model_id","benchmark_id"]).sum())
print(d.performance.describe())
m = d.pivot_table(index="model", columns="benchmark", values="performance", aggfunc="mean")
print("matrix", m.shape, "density", m.notna().mean().mean().round(3))
c = m.notna().sum().sort_values(ascending=False)
print(c.to_string())
print("models by #benchmarks:", m.notna().sum(axis=1).value_counts().sort_index().to_dict())
